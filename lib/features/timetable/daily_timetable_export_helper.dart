import 'dart:typed_data';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:excel/excel.dart' as ex;
import '../../core/models/daily_timetable.dart';

class DailyTimetableExportHelper {
  static Future<void> exportPdf(DailyTimetable timetable) async {
    final pdf = pw.Document();

    pdf.addPage(
      pw.Page(
        pageFormat: PdfPageFormat.a4.landscape,
        margin: const pw.EdgeInsets.all(24),
        build: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              // Header
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.start,
                    children: [
                      pw.Text(
                        'MALABAR INSTITUTE OF PARAMEDICAL SCIENCE',
                        style: pw.TextStyle(fontSize: 16, fontWeight: pw.FontWeight.bold, color: PdfColors.blue900),
                      ),
                      pw.SizedBox(height: 2),
                      pw.Text(
                        'Daily Lecture & Clinical Training Schedule',
                        style: pw.TextStyle(fontSize: 12, color: PdfColors.grey700),
                      ),
                    ],
                  ),
                  pw.Column(
                    crossAxisAlignment: pw.CrossAxisAlignment.end,
                    children: [
                      pw.Text('Date: ${timetable.date}', style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold)),
                      pw.Text(
                        'Status: ${timetable.status.toUpperCase()}',
                        style: pw.TextStyle(
                          fontSize: 11,
                          fontWeight: pw.FontWeight.bold,
                          color: timetable.isPublished ? PdfColors.green800 : PdfColors.amber800,
                        ),
                      ),
                    ],
                  ),
                ],
              ),
              pw.SizedBox(height: 12),
              pw.Divider(color: PdfColors.grey400, thickness: 1),
              pw.SizedBox(height: 12),

              // Table
              pw.TableHelper.fromTextArray(
                headers: ['Time Slot', 'Course', 'Year', 'Subject', 'Teacher / Faculty', 'Class / Room'],
                headerStyle: pw.TextStyle(fontSize: 10, fontWeight: pw.FontWeight.bold, color: PdfColors.white),
                headerDecoration: const pw.BoxDecoration(color: PdfColors.blue800),
                cellStyle: const pw.TextStyle(fontSize: 9),
                cellHeight: 24,
                cellAlignment: pw.Alignment.centerLeft,
                data: timetable.entries.map((e) {
                  return [
                    '${e.startTime} - ${e.endTime}',
                    e.courseName,
                    e.year,
                    e.subjectName,
                    e.teacherName,
                    e.classRoom,
                  ];
                }).toList(),
              ),

              pw.Spacer(),
              pw.Divider(color: PdfColors.grey300),
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text('Generated by MIPS ERP System', style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600)),
                  pw.Text('Official Institutional Document', style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey600)),
                ],
              ),
            ],
          );
        },
      ),
    );

    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdf.save(),
      name: 'MIPS_Timetable_${timetable.date}.pdf',
    );
  }

  static Future<Uint8List> exportExcel(DailyTimetable timetable) async {
    final excel = ex.Excel.createExcel();
    final sheet = excel['Daily Schedule'];
    excel.setDefaultSheet('Daily Schedule');

    // Headers
    sheet.appendRow([
      ex.TextCellValue('Date: ${timetable.date}'),
      ex.TextCellValue('Status: ${timetable.status.toUpperCase()}'),
    ]);
    sheet.appendRow([ex.TextCellValue('')]); // empty line

    sheet.appendRow([
      ex.TextCellValue('Start Time'),
      ex.TextCellValue('End Time'),
      ex.TextCellValue('Course'),
      ex.TextCellValue('Year'),
      ex.TextCellValue('Subject'),
      ex.TextCellValue('Teacher'),
      ex.TextCellValue('Class / Room'),
    ]);

    for (final e in timetable.entries) {
      sheet.appendRow([
        ex.TextCellValue(e.startTime),
        ex.TextCellValue(e.endTime),
        ex.TextCellValue(e.courseName),
        ex.TextCellValue(e.year),
        ex.TextCellValue(e.subjectName),
        ex.TextCellValue(e.teacherName),
        ex.TextCellValue(e.classRoom),
      ]);
    }

    final bytes = excel.encode();
    return Uint8List.fromList(bytes ?? []);
  }
}
