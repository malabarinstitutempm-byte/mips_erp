CREATE OR REPLACE VIEW view_student_fee_summary AS
SELECT 
    s.id AS student_id,
    s.admission_number,
    s.name AS student_name,
    coalesce(sum(fi.amount_paise), 0) AS total_fee_paise,
    coalesce(sum(fi.paid_amount_paise), 0) AS paid_amount_paise,
    coalesce(sum(fi.amount_paise - fi.paid_amount_paise), 0) AS pending_amount_paise
FROM students s
LEFT JOIN student_enrollments se ON se.student_id = s.id AND se.deleted_at IS NULL AND se.status = 'active'
LEFT JOIN fee_items fi ON fi.enrollment_id = se.id AND fi.deleted_at IS NULL
WHERE s.deleted_at IS NULL
GROUP BY s.id, s.admission_number, s.name;

CREATE OR REPLACE VIEW view_course_financial_summary AS
SELECT 
    c.id AS course_id,
    c.name AS course_name,
    c.code AS course_code,
    c.course_type,
    c.structure,
    count(DISTINCT s.id) AS total_students,
    coalesce(sum(f.total_fee_paise), 0) AS total_revenue_paise,
    coalesce(sum(f.paid_amount_paise), 0) AS total_collected_paise,
    coalesce(sum(f.pending_amount_paise), 0) AS total_pending_paise,
    round(coalesce(sum(f.total_fee_paise), 0) / 100.0, 2) AS total_revenue_inr,
    round(coalesce(sum(f.paid_amount_paise), 0) / 100.0, 2) AS total_collected_inr,
    round(coalesce(sum(f.pending_amount_paise), 0) / 100.0, 2) AS total_pending_inr
FROM courses c
LEFT JOIN students s ON s.course_id = c.id AND s.deleted_at IS NULL
LEFT JOIN fees f ON f.student_id = s.id AND f.deleted_at IS NULL
WHERE c.deleted_at IS NULL
GROUP BY c.id, c.name, c.code, c.course_type, c.structure;

CREATE OR REPLACE VIEW view_fee_defaulters AS
SELECT 
    s.id AS student_id,
    s.name AS student_name,
    coalesce(s.admission_number, 'N/A') AS admission_number,
    coalesce(s.phone, 'N/A') AS phone,
    s.course_id,
    s.batch_id,
    coalesce(c.name, 'N/A') AS course_name,
    coalesce(b.batch_name, 'N/A') AS batch_name,
    f.total_fee_paise,
    f.paid_amount_paise,
    f.pending_amount_paise,
    round(f.pending_amount_paise / 100.0, 2) AS pending_amount_inr,
    coalesce(to_char(s.admission_date, 'YYYY-MM-DD'), '-') AS due_date
FROM students s
JOIN fees f ON f.student_id = s.id AND f.deleted_at IS NULL
LEFT JOIN courses c ON s.course_id = c.id
LEFT JOIN batches b ON s.batch_id = b.id
WHERE s.deleted_at IS NULL
  AND f.pending_amount_paise > 0;

CREATE OR REPLACE VIEW view_fee_collection_daily AS
SELECT 
    p.payment_date,
    p.payment_mode::text AS payment_mode,
    count(p.id) AS transaction_count,
    sum(p.amount_paise) AS total_amount_paise,
    round(sum(p.amount_paise) / 100.0, 2) AS total_amount_inr
FROM payments p
WHERE p.deleted_at IS NULL
  AND p.is_cancelled = false
GROUP BY p.payment_date, p.payment_mode::text;

-- 5. Core RPC Functions (Unified Architecture)
CREATE OR REPLACE FUNCTION promote_batch_period(
    p_batch_id bigint,
    p_to_period int DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_batch record;
    v_current int;
    v_next int;
    v_total_periods int;
BEGIN
    SELECT b.id, b.course_id, b.period_type, b.current_period, c.duration, c.structure
    INTO v_batch
    FROM batches b
    JOIN courses c ON c.id = b.course_id
    WHERE b.id = p_batch_id AND b.deleted_at IS NULL;

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'error', 'Batch not found');
    END IF;

    v_current := coalesce(v_batch.current_period, 1);
    v_next := coalesce(p_to_period, v_current + 1);

    -- Complete current period in batch_periods
    UPDATE batch_periods 
    SET status = 'completed', updated_at = clock_timestamp()
    WHERE batch_id = p_batch_id AND period_no = v_current;

    -- Ensure next period exists and is active
    INSERT INTO batch_periods (batch_id, period_type, period_no, status)
    VALUES (p_batch_id, v_batch.period_type, v_next, 'active')
    ON CONFLICT (batch_id, period_no)
    DO UPDATE SET status = 'active', updated_at = clock_timestamp();

    -- Update batch current period
    UPDATE batches
    SET current_period = v_next,
        updated_at = clock_timestamp()
    WHERE id = p_batch_id;

    RETURN jsonb_build_object(
        'success', true, 
        'batch_id', p_batch_id, 
        'previous_period', v_current, 
        'current_period', v_next,
        'period_type', v_batch.period_type
    );
END;
$$;
GRANT EXECUTE ON FUNCTION promote_batch_period(bigint, int) TO authenticated;

