-- 3. Create Batch Periods & Daily Timetables Tables
CREATE TABLE IF NOT EXISTS batch_periods (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id bigint NOT NULL REFERENCES batches(id) ON DELETE CASCADE,
    period_type text NOT NULL DEFAULT 'year' CHECK (period_type IN ('semester', 'year', 'single')),
    period_no int NOT NULL CHECK (period_no >= 1 AND period_no <= 12),
    start_date date,
    end_date date,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed', 'upcoming')),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (batch_id, period_no)
);

CREATE TABLE IF NOT EXISTS daily_timetables (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id bigint NOT NULL REFERENCES batches(id) ON DELETE CASCADE,
    timetable_date date NOT NULL,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'cancelled', 'holiday')),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (batch_id, timetable_date)
);

CREATE TABLE IF NOT EXISTS daily_timetable_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_timetable_id bigint NOT NULL REFERENCES daily_timetables(id) ON DELETE CASCADE,
    subject_id bigint NOT NULL REFERENCES course_subjects(id) ON DELETE CASCADE,
    teacher_id bigint REFERENCES teachers(id),
    slot text NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    room text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (daily_timetable_id, slot, start_time)
);

