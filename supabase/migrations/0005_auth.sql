-- Record an attempt (called by Edge Function / auth server)
CREATE OR REPLACE FUNCTION record_login_attempt(
    p_identifier_hash text,
    p_ip text,
    p_success boolean
)
RETURNS void AS $$
BEGIN
    INSERT INTO login_attempts (identifier_hash, ip, success, attempted_at)
    VALUES (p_identifier_hash, p_ip, p_success, clock_timestamp());
END;
$$ LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp;

GRANT EXECUTE ON FUNCTION record_login_attempt(text, text, boolean) TO service_role;

-- Calculate failure metrics across both identifier and IP
-- Evaluates unknown identifiers identically to existing ones (anti-enumeration)
CREATE OR REPLACE FUNCTION get_login_failure_metrics(
    p_identifier_hash text,
    p_ip text,
    p_window_minutes int DEFAULT 15
)
RETURNS jsonb AS $$
DECLARE
    v_window_start timestamptz;
    v_id_failures int := 0;
    v_ip_failures int := 0;
    v_last_success timestamptz;
    v_max_attempts int := 5;
    v_captcha_threshold int := 3;
BEGIN
    v_window_start := clock_timestamp() - (p_window_minutes || ' minutes')::interval;

    -- Look up last successful login for this identifier to count only subsequent failures
    SELECT MAX(attempted_at) INTO v_last_success
    FROM login_attempts
    WHERE identifier_hash = p_identifier_hash 
      AND success = true 
      AND attempted_at >= v_window_start;

    -- Count failed attempts for identifier since last success (or window start)
    SELECT COUNT(*) INTO v_id_failures
    FROM login_attempts
    WHERE identifier_hash = p_identifier_hash
      AND success = false
      AND attempted_at >= COALESCE(v_last_success, v_window_start);

    -- Count failed attempts for IP in window
    SELECT COUNT(*) INTO v_ip_failures
    FROM login_attempts
    WHERE ip = p_ip
      AND success = false
      AND attempted_at >= v_window_start;

    -- Read dynamic thresholds if available in settings
    SELECT COALESCE(value::int, 5) INTO v_max_attempts
    FROM settings WHERE key = 'max_failed_attempts';

    SELECT COALESCE(value::int, 3) INTO v_captcha_threshold
    FROM settings WHERE key = 'captcha_after_failures';

    RETURN jsonb_build_object(
        'identifier_failures', v_id_failures,
        'ip_failures', v_ip_failures,
        'requires_captcha', (v_id_failures >= v_captcha_threshold OR v_ip_failures >= v_captcha_threshold),
        'is_locked', (v_id_failures >= v_max_attempts),
        'max_attempts', v_max_attempts,
        'attempts_remaining', GREATEST(0, v_max_attempts - v_id_failures)
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER STABLE
SET search_path = public, pg_temp;

GRANT EXECUTE ON FUNCTION get_login_failure_metrics(text, text, int) TO service_role;

-- =============================================================================
-- 6. Structured Admin Action Audit Logging (Zero Secret Leakage)
-- =============================================================================

CREATE OR REPLACE FUNCTION log_admin_action(
    p_action text,
    p_target text,
    p_details jsonb DEFAULT '{}'::jsonb
)
RETURNS void AS $$
DECLARE
    v_actor uuid := auth.uid();
BEGIN
    -- Strip any accidental sensitive keys from details
    p_details := p_details - 'password' - 'temp_password' - 'secret' - 'service_key';

    INSERT INTO audit_log (table_name, record_id, action, new_data, actor, created_at)
    VALUES (
        'admin_security',
        p_target,
        p_action,
        p_details,
        v_actor,
        clock_timestamp()
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp;

GRANT EXECUTE ON FUNCTION log_admin_action(text, text, jsonb) TO authenticated, service_role;

-- =============================================================================
-- 7. Account Unlock Admin Procedure
-- =============================================================================

CREATE OR REPLACE FUNCTION admin_unlock_user(
    p_target_user_id uuid
)
RETURNS jsonb AS $$
DECLARE
    v_profile profiles%ROWTYPE;
BEGIN
    IF NOT is_admin() THEN
        RAISE EXCEPTION 'Access denied: Only administrators can unlock user accounts.';
    END IF;

    SELECT * INTO v_profile
    FROM profiles
    WHERE user_id = p_target_user_id;

    IF NOT FOUND THEN
        RETURN jsonb_build_object('success', false, 'error', 'Target user profile not found');
    END IF;

    UPDATE profiles
    SET failed_attempts = 0,
        locked_at = NULL,
        active = true,
        updated_at = clock_timestamp()
    WHERE user_id = p_target_user_id;

    -- Write to audit log without exposing secrets
    PERFORM log_admin_action(
        'UNLOCK_ACCOUNT',
        p_target_user_id::text,
        jsonb_build_object(
            'target_user_id', p_target_user_id,
            'role', v_profile.role,
            'action', 'Account unlocked and failure counter reset'
        )
    );

    RETURN jsonb_build_object(
        'success', true, 
        'message', 'Account successfully unlocked and failed attempts reset.'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp;

GRANT EXECUTE ON FUNCTION admin_unlock_user(uuid) TO authenticated;
