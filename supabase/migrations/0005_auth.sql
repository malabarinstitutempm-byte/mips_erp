-- =============================================================================
-- 4. MFA-Aware is_admin() Function
-- =============================================================================

CREATE OR REPLACE FUNCTION is_admin()
RETURNS boolean AS $$
DECLARE
    v_is_admin boolean := false;
    v_require_mfa boolean := false;
    v_aal text;
BEGIN
    -- 1. Check if user has active admin role in profiles
    SELECT EXISTS (
        SELECT 1 FROM profiles
        WHERE user_id = auth.uid() 
          AND role = 'admin' 
          AND active = true
    ) INTO v_is_admin;

    IF NOT v_is_admin THEN
        RETURN false;
    END IF;

    -- 2. Inspect require_admin_mfa setting
    SELECT COALESCE(value = 'true', false) INTO v_require_mfa
    FROM settings
    WHERE key = 'require_admin_mfa';

    -- 3. When require_admin_mfa is true, require aal2 (TOTP verified) in JWT claims
    IF v_require_mfa THEN
        v_aal := auth.jwt() ->> 'aal';
        IF v_aal IS NULL OR v_aal != 'aal2' THEN
            RETURN false;
        END IF;
    END IF;

    RETURN true;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER STABLE
SET search_path = public, pg_temp;

GRANT EXECUTE ON FUNCTION is_admin() TO authenticated;

