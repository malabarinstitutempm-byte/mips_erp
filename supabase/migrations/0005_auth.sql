BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='failed_attempts') THEN
        ALTER TABLE profiles ADD COLUMN failed_attempts int NOT NULL DEFAULT 0;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='profiles' AND column_name='locked_at') THEN
        ALTER TABLE profiles ADD COLUMN locked_at timestamptz;
    END IF;
END $$;

-- =============================================================================
-- 2. Login Attempts Table (Universal Identifiers & Anti-Enumeration)
-- =============================================================================

CREATE TABLE IF NOT EXISTS login_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    identifier_hash text NOT NULL,
    ip text NOT NULL,
    success boolean NOT NULL DEFAULT false,
    attempted_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Fast lookup indexes for sliding window checks
CREATE INDEX IF NOT EXISTS idx_login_attempts_id_hash_time ON login_attempts (identifier_hash, attempted_at DESC);
CREATE INDEX IF NOT EXISTS idx_login_attempts_ip_time ON login_attempts (ip, attempted_at DESC);

-- Enable RLS and lockdown: completely inaccessible to client keys
ALTER TABLE login_attempts ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON login_attempts FROM anon, authenticated, PUBLIC;
GRANT SELECT, INSERT ON login_attempts TO service_role;

-- Revoke update and delete to preserve audit immutability
REVOKE UPDATE, DELETE ON login_attempts FROM PUBLIC, anon, authenticated, service_role;

