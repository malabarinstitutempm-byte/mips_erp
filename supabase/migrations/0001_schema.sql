-- Universal updated_at timestamp maintainer
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Universal Audit Trigger Function
CREATE OR REPLACE FUNCTION audit_log_trigger()
RETURNS TRIGGER AS $$
DECLARE
    rec_id text;
    actor_id uuid;
    old_row jsonb := null;
    new_row jsonb := null;
    action_type text;
BEGIN
    BEGIN
        actor_id := auth.uid();
    EXCEPTION WHEN OTHERS THEN
        actor_id := null;
    END;

    IF TG_OP = 'INSERT' THEN
        action_type := 'INSERT';
        new_row := to_jsonb(NEW);
        rec_id := coalesce((to_jsonb(NEW)->>'id'), '');
    ELSIF TG_OP = 'UPDATE' THEN
        IF (to_jsonb(NEW)->>'deleted_at') IS NOT NULL AND (to_jsonb(OLD)->>'deleted_at') IS NULL THEN
            action_type := 'SOFT_DELETE';
        ELSE
            action_type := 'UPDATE';
        END IF;
        old_row := to_jsonb(OLD);
        new_row := to_jsonb(NEW);
        rec_id := coalesce((to_jsonb(NEW)->>'id'), (to_jsonb(OLD)->>'id'), '');
    ELSIF TG_OP = 'DELETE' THEN
        action_type := 'DELETE';
        old_row := to_jsonb(OLD);
        rec_id := coalesce((to_jsonb(OLD)->>'id'), '');
    END IF;

    INSERT INTO audit_log (table_name, record_id, action, old_data, new_data, actor, created_at)
    VALUES (TG_TABLE_NAME, rec_id, action_type, old_row, new_row, actor_id, clock_timestamp());

    RETURN coalesce(NEW, OLD);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp;

