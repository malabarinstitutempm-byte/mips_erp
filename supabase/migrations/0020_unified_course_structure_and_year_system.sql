RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO batch_periods (batch_id, period_type, period_no, start_date, end_date, status)
        VALUES (NEW.batch_id, 'semester', NEW.semester_no, NEW.start_date, NEW.end_date, coalesce(NEW.status, 'active'))
        RETURNING id INTO NEW.id;
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        UPDATE batch_periods
        SET start_date = NEW.start_date,
            end_date = NEW.end_date,
            status = NEW.status,
            period_no = NEW.semester_no,
            updated_at = clock_timestamp()
        WHERE id = OLD.id;
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        DELETE FROM batch_periods WHERE id = OLD.id;
        RETURN OLD;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

