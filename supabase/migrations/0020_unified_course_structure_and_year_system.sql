-- Helper: total period count for a course
CREATE OR REPLACE FUNCTION course_periods_count(p_course_id bigint)
RETURNS int AS $$
DECLARE
    v_structure text;
    v_dur_years int;
BEGIN
    SELECT structure INTO v_structure FROM courses WHERE id = p_course_id;
    IF v_structure IS NULL THEN RETURN 4; END IF;
    
    IF v_structure = 'single' THEN
        RETURN 1;
    END IF;

    v_dur_years := course_duration_years(p_course_id);
    IF v_structure = 'year' THEN
        RETURN GREATEST(1, v_dur_years);
    ELSE
        -- semester-wise: years * 2
        RETURN GREATEST(1, v_dur_years * 2);
    END IF;
END;
$$ LANGUAGE plpgsql STABLE
SET search_path = public, pg_temp;

-- Trigger: Course structure cannot be changed once exams, marks or attendance sessions exist
CREATE OR REPLACE FUNCTION check_course_structure_locked()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.structure IS DISTINCT FROM NEW.structure THEN
        -- Check exams
        IF EXISTS (SELECT 1 FROM exams WHERE course_id = NEW.id AND deleted_at IS NULL) THEN
            RAISE EXCEPTION 'Cannot alter structure for course "%" (ID %). Course structure is locked because exams already exist.',
                NEW.name, NEW.id;
        END IF;

        -- Check attendance sessions
        IF EXISTS (
            SELECT 1 FROM attendance_sessions s
            JOIN batches b ON b.id = s.batch_id
            WHERE b.course_id = NEW.id
        ) THEN
            RAISE EXCEPTION 'Cannot alter structure for course "%" (ID %). Course structure is locked because attendance sessions already exist.',
                NEW.name, NEW.id;
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql
SET search_path = public, pg_temp;

DROP TRIGGER IF EXISTS trg_check_course_structure_locked ON courses;
CREATE TRIGGER trg_check_course_structure_locked
    BEFORE UPDATE OF structure ON courses
    FOR EACH ROW EXECUTE FUNCTION check_course_structure_locked();


