-- 9. YEAR-WISE PROMOTION FUNCTION: promote_year
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION preview_promote_year(
    p_batch_id bigint,
    p_closing_end_date date,
    p_new_start_date date
)
RETURNS jsonb AS $$
DECLARE
    v_b batches%ROWTYPE;
    v_c courses%ROWTYPE;
    v_active_period batch_periods%ROWTYPE;
    v_curr_year int;
    v_next_year int;
    v_max_years int;
    v_student_count int;
BEGIN
    SELECT * INTO v_b FROM batches WHERE id = p_batch_id AND deleted_at IS NULL;
    IF NOT FOUND THEN RAISE EXCEPTION 'Batch ID % does not exist.', p_batch_id; END IF;

    SELECT * INTO v_c FROM courses WHERE id = v_b.course_id;
    IF v_c.structure != 'year' THEN
        RAISE EXCEPTION 'Course "%" has structure "%". Use promote_semester for semester-wise courses.',
            v_c.name, v_c.structure;
    END IF;

    v_curr_year := v_b.current_year;
    v_next_year := v_curr_year + 1;
    v_max_years := course_duration_years(v_c.id);

    IF v_curr_year >= v_max_years THEN
        RAISE EXCEPTION 'Batch % is already in its final Year (% of %). Cannot promote further. Use complete_batch to graduate.',
            v_b.name, v_curr_year, v_max_years;
    END IF;

    IF p_closing_end_date >= p_new_start_date THEN
        RAISE EXCEPTION 'New Year start date (%) must be strictly after closing end date (%).',
            p_new_start_date, p_closing_end_date;
    END IF;

    SELECT * INTO v_active_period 
    FROM batch_periods 
    WHERE batch_id = p_batch_id AND period_type = 'year' AND period_no = v_curr_year;

    IF FOUND AND p_closing_end_date < v_active_period.start_date THEN
        RAISE EXCEPTION 'Closing end date (%) cannot be earlier than current Year start date (%).',
            p_closing_end_date, v_active_period.start_date;
    END IF;

    SELECT count(*) INTO v_student_count
    FROM enrollments
    WHERE batch_id = p_batch_id AND status = 'active';

    RETURN jsonb_build_object(
        'batch_id', p_batch_id,
        'batch_name', v_b.name,
        'course_name', v_c.name,
        'current_year', v_curr_year,
        'next_year', v_next_year,
        'max_years', v_max_years,
        'active_students_count', v_student_count,
        'closing_end_date', p_closing_end_date,
        'new_start_date', p_new_start_date
    );
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER;


CREATE OR REPLACE FUNCTION promote_year(
    p_batch_id bigint,
    p_closing_end_date date,
    p_new_start_date date,
    p_override_reason text DEFAULT NULL
)
RETURNS jsonb AS $$
DECLARE
    v_b batches%ROWTYPE;
    v_c courses%ROWTYPE;
    v_curr_year int;
    v_next_year int;
    v_max_years int;
    v_preview jsonb;
    v_notif_count int := 0;
BEGIN
    IF NOT is_admin() THEN
        RAISE EXCEPTION 'Access denied. Administrator privilege required to promote batches.';
    END IF;

    v_preview := preview_promote_year(p_batch_id, p_closing_end_date, p_new_start_date);
    
    SELECT * INTO v_b FROM batches WHERE id = p_batch_id;
    SELECT * INTO v_c FROM courses WHERE id = v_b.course_id;

    v_curr_year := v_b.current_year;
    v_next_year := v_curr_year + 1;
    v_max_years := course_duration_years(v_c.id);

    -- 1. Close current year in batch_periods
    UPDATE batch_periods
    SET end_date = p_closing_end_date,
        status = 'closed',
        updated_at = clock_timestamp()
    WHERE batch_id = p_batch_id AND period_type = 'year' AND period_no = v_curr_year;

    -- 2. Open new year in batch_periods
    INSERT INTO batch_periods (batch_id, period_type, period_no, start_date, end_date, status)
    VALUES (p_batch_id, 'year', v_next_year, p_new_start_date, NULL, 'active')
    ON CONFLICT (batch_id, period_type, period_no)
    DO UPDATE SET
        start_date = EXCLUDED.start_date,
        end_date = NULL,
        status = 'active',
        updated_at = clock_timestamp();

    -- 3. Update batch
    UPDATE batches
    SET current_year = v_next_year,
        current_semester = v_next_year * 2,
        updated_at = clock_timestamp()
    WHERE id = p_batch_id;

    -- 4. Audit Log
    INSERT INTO audit_logs (
        table_name, record_id, action, old_data, new_data, performed_by, reason, created_at
    ) VALUES (
        'batches',
        p_batch_id,
        'PROMOTE_YEAR',
        jsonb_build_object('year_no', v_curr_year, 'end_date', p_closing_end_date),
        jsonb_build_object('year_no', v_next_year, 'start_date', p_new_start_date),
        auth.uid(),
        coalesce(p_override_reason, 'Promoted to next academic year'),
        clock_timestamp()
    );

    -- 5. Notify active students
    INSERT INTO notifications (user_id, type, title, body, link, created_at)
    SELECT 
        p.user_id,
        'promotion',
        'Academic Year Promotion',
        'Congratulations! You have been promoted to Year ' || v_next_year || ' for ' || v_c.name || '.',
        '/attendance',
        clock_timestamp()
    FROM enrollments e
    JOIN profiles p ON p.student_id = e.student_id AND p.role = 'student' AND p.active = true
    WHERE e.batch_id = p_batch_id AND e.status = 'active';

    GET DIAGNOSTICS v_notif_count = ROW_COUNT;

    RETURN jsonb_build_object(
        'success', true,
        'batch_id', p_batch_id,
        'previous_year', v_curr_year,
        'current_year', v_next_year,
        'notified_students', v_notif_count
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- -----------------------------------------------------------------------------
-- 10. REVISE promote_semester: REJECT NON-SEMESTER COURSES
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION preview_promote_semester(
    p_batch_id bigint,
    p_closing_end_date date,
    p_new_start_date date
)
RETURNS jsonb AS $$
DECLARE
    v_b batches%ROWTYPE;
    v_c courses%ROWTYPE;
    v_active_sem batch_periods%ROWTYPE;
    v_curr_sem int;
    v_next_sem int;
    v_max_sems int;
    v_student_count int;
BEGIN
    SELECT * INTO v_b FROM batches WHERE id = p_batch_id AND deleted_at IS NULL;
    IF NOT FOUND THEN RAISE EXCEPTION 'Batch ID % does not exist.', p_batch_id; END IF;

    SELECT * INTO v_c FROM courses WHERE id = v_b.course_id;
    IF v_c.structure != 'semester' THEN
        RAISE EXCEPTION 'Course "%" has structure "%". Use promote_year for year-wise courses.',
            v_c.name, v_c.structure;
    END IF;

    v_curr_sem := v_b.current_semester;
    v_next_sem := v_curr_sem + 1;
    v_max_sems := course_duration_years(v_c.id) * 2;

    IF v_curr_sem >= v_max_sems THEN
        RAISE EXCEPTION 'Batch % is already in its final Semester (% of %). Cannot promote further. Use complete_batch to graduate.',
            v_b.name, v_curr_sem, v_max_sems;
    END IF;

    IF p_closing_end_date >= p_new_start_date THEN
        RAISE EXCEPTION 'New semester start date (%) must be strictly after closing end date (%).',
            p_new_start_date, p_closing_end_date;
    END IF;

    SELECT * INTO v_active_sem 
    FROM batch_periods 
    WHERE batch_id = p_batch_id AND period_type = 'semester' AND period_no = v_curr_sem;

    IF FOUND AND p_closing_end_date < v_active_sem.start_date THEN
        RAISE EXCEPTION 'Closing end date (%) cannot be earlier than current semester start date (%).',
            p_closing_end_date, v_active_sem.start_date;
    END IF;

    SELECT count(*) INTO v_student_count
    FROM enrollments
    WHERE batch_id = p_batch_id AND status = 'active';

    RETURN jsonb_build_object(
        'batch_id', p_batch_id,
        'batch_name', v_b.name,
        'course_name', v_c.name,
        'current_semester', v_curr_sem,
        'next_semester', v_next_sem,
        'max_semesters', v_max_sems,
        'active_students_count', v_student_count,
        'closing_end_date', p_closing_end_date,
        'new_start_date', p_new_start_date
    );
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER;


CREATE OR REPLACE FUNCTION promote_semester(
    p_batch_id bigint,
    p_closing_end_date date,
    p_new_start_date date,
    p_override_reason text DEFAULT NULL
)
RETURNS jsonb AS $$
DECLARE
    v_b batches%ROWTYPE;
    v_c courses%ROWTYPE;
    v_curr_sem int;
    v_next_sem int;
    v_next_year int;
    v_max_sems int;
    v_preview jsonb;
    v_notif_count int := 0;
BEGIN
    IF NOT is_admin() THEN
        RAISE EXCEPTION 'Access denied. Administrator privilege required to promote batches.';
    END IF;

    v_preview := preview_promote_semester(p_batch_id, p_closing_end_date, p_new_start_date);
    
    SELECT * INTO v_b FROM batches WHERE id = p_batch_id;
    SELECT * INTO v_c FROM courses WHERE id = v_b.course_id;

    v_curr_sem := v_b.current_semester;
    v_next_sem := v_curr_sem + 1;
    v_next_year := ceil(v_next_sem::numeric / 2.0)::int;
    v_max_sems := course_duration_years(v_c.id) * 2;

    -- 1. Close current semester in batch_periods
    UPDATE batch_periods
    SET end_date = p_closing_end_date,
        status = 'closed',
        updated_at = clock_timestamp()
    WHERE batch_id = p_batch_id AND period_type = 'semester' AND period_no = v_curr_sem;

    -- 2. Open new semester in batch_periods
    INSERT INTO batch_periods (batch_id, period_type, period_no, start_date, end_date, status)
    VALUES (p_batch_id, 'semester', v_next_sem, p_new_start_date, NULL, 'active')
    ON CONFLICT (batch_id, period_type, period_no)
    DO UPDATE SET
        start_date = EXCLUDED.start_date,
        end_date = NULL,
        status = 'active',
        updated_at = clock_timestamp();

    -- 3. Update batch
    UPDATE batches
    SET current_semester = v_next_sem,
        current_year = v_next_year,
        updated_at = clock_timestamp()
    WHERE id = p_batch_id;

    -- 4. Audit Log
    INSERT INTO audit_logs (
        table_name, record_id, action, old_data, new_data, performed_by, reason, created_at
    ) VALUES (
        'batches',
        p_batch_id,
        'PROMOTE_SEMESTER',
        jsonb_build_object('semester_no', v_curr_sem, 'end_date', p_closing_end_date),
        jsonb_build_object('semester_no', v_next_sem, 'start_date', p_new_start_date, 'year', v_next_year),
        auth.uid(),
        coalesce(p_override_reason, 'Promoted to next semester'),
        clock_timestamp()
    );

    -- 5. Notify active students
    INSERT INTO notifications (user_id, type, title, body, link, created_at)
    SELECT 
        p.user_id,
        'promotion',
        'Semester Promotion',
        'Congratulations! You have been promoted to Semester ' || v_next_sem || ' (Year ' || v_next_year || ') for ' || v_c.name || '.',
        '/attendance',
        clock_timestamp()
    FROM enrollments e
    JOIN profiles p ON p.student_id = e.student_id AND p.role = 'student' AND p.active = true
    WHERE e.batch_id = p_batch_id AND e.status = 'active';

    GET DIAGNOSTICS v_notif_count = ROW_COUNT;

    RETURN jsonb_build_object(
        'success', true,
        'batch_id', p_batch_id,
        'previous_semester', v_curr_sem,
        'current_semester', v_next_sem,
        'current_year', v_next_year,
        'notified_students', v_notif_count
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- -----------------------------------------------------------------------------
-- 11. PUBLISH EXAM: Notification Text for Semester vs Year
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION publish_exam(
    p_exam_id bigint,
    p_force_notify boolean DEFAULT false
)
RETURNS jsonb AS $$
DECLARE
    v_exam exams%ROWTYPE;
    v_was_published boolean;
    v_results_count int;
    v_notif_count int := 0;
    v_title text;
    v_body text;
BEGIN
    IF NOT is_admin() THEN
        RAISE EXCEPTION 'Access denied. Administrator privilege required to publish exams.';
    END IF;

    SELECT * INTO v_exam FROM exams WHERE id = p_exam_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Exam ID % does not exist.', p_exam_id;
    END IF;

    -- Ensure results have been computed first
    SELECT count(*) INTO v_results_count
    FROM results
    WHERE exam_id = p_exam_id AND deleted_at IS NULL;

    IF v_results_count = 0 THEN
        RAISE EXCEPTION 'Cannot publish exam: results have not yet been computed.';
    END IF;

    v_was_published := (v_exam.status = 'published');

    -- Update exam status
    UPDATE exams
    SET status = 'published',
        published_at = coalesce(published_at, clock_timestamp()),
        publish_date = coalesce(publish_date, CURRENT_DATE),
        updated_at = clock_timestamp()
    WHERE id = p_exam_id;

    -- Compute title & body
    IF v_exam.period_type = 'year' AND v_exam.period_no IS NOT NULL THEN
        v_title := 'Year ' || v_exam.period_no || ' Result Published';
        v_body := 'Year ' || v_exam.period_no || ' results for "' || v_exam.name || '" are now published. You can view your marksheet.';
    ELSIF v_exam.period_type = 'semester' AND v_exam.period_no IS NOT NULL THEN
        v_title := 'Semester ' || v_exam.period_no || ' Result Published';
        v_body := 'Semester ' || v_exam.period_no || ' results for "' || v_exam.name || '" are now published. You can view your marksheet.';
    ELSE
        v_title := 'Exam Results Published';
        v_body := 'Results for "' || v_exam.name || '" are now published. You can view your marksheet.';
    END IF;

    -- Dispatch notifications to students if first time or forced
    IF (NOT v_was_published) OR p_force_notify THEN
        INSERT INTO notifications (user_id, type, title, body, link, created_at)
        SELECT 
            p.user_id,
            'result_published',
            v_title,
            v_body,
            '/results/' || p_exam_id::text,
            clock_timestamp()
        FROM results r
        JOIN profiles p ON p.student_id = r.student_id AND p.role = 'student' AND p.active = true
        WHERE r.exam_id = p_exam_id AND r.deleted_at IS NULL;

        GET DIAGNOSTICS v_notif_count = ROW_COUNT;
    END IF;

    RETURN jsonb_build_object(
        'success', true,
        'exam_id', p_exam_id,
        'notifications_sent', v_notif_count
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- -----------------------------------------------------------------------------
-- 12. COMPUTE RESULTS: Ensure period_type and period_no are populated
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION compute_results(
    p_exam_id bigint
)
RETURNS jsonb AS $$
DECLARE
    v_exam exams%ROWTYPE;
    v_student record;
    v_mark record;
    v_total_max numeric(6,2) := 0;
    v_total_obtained numeric(6,2);
    v_pct numeric(5,2);
    v_has_failed boolean;
    v_grade text;
    v_status text;
    v_computed_count int := 0;
    v_pass_count int := 0;
    v_fail_count int := 0;
BEGIN
    IF NOT is_admin() THEN
        RAISE EXCEPTION 'Access denied. Administrator privilege required to compute results.';
    END IF;

    SELECT * INTO v_exam FROM exams WHERE id = p_exam_id AND deleted_at IS NULL;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Exam with ID % does not exist or has been deleted.', p_exam_id;
    END IF;

    -- Calculate total maximum possible marks across all exam subjects
    SELECT coalesce(sum(max_marks), 0) INTO v_total_max
    FROM exam_subjects
    WHERE exam_id = p_exam_id AND deleted_at IS NULL;

    IF v_total_max <= 0 THEN
        RAISE EXCEPTION 'Exam has no configured subjects or maximum marks.';
    END IF;

    -- Loop through all students who have entered marks for this exam
    FOR v_student IN 
        SELECT DISTINCT student_id 
        FROM marks 
        WHERE exam_id = p_exam_id AND deleted_at IS NULL
    LOOP
        v_total_obtained := 0;
        v_has_failed := false;

        -- Verify every subject in this exam
        FOR v_mark IN
            SELECT es.id as subject_id, es.pass_marks, es.max_marks,
                   m.marks_obtained, m.is_absent
            FROM exam_subjects es
            LEFT JOIN marks m ON m.subject_id = es.id 
                             AND m.student_id = v_student.student_id 
                             AND m.exam_id = p_exam_id 
                             AND m.deleted_at IS NULL
            WHERE es.exam_id = p_exam_id AND es.deleted_at IS NULL
        LOOP
            IF v_mark.is_absent = true OR v_mark.marks_obtained IS NULL THEN
                v_has_failed := true;
            ELSE
                v_total_obtained := v_total_obtained + v_mark.marks_obtained;
                IF v_mark.marks_obtained < v_mark.pass_marks THEN
                    v_has_failed := true;
                END IF;
            END IF;
        END LOOP;

        v_pct := round((v_total_obtained / v_total_max) * 100.0, 2);

        -- Determine grade based on configured grading scheme
        SELECT grade INTO v_grade
        FROM grading_schemes
        WHERE v_pct >= min_percent AND v_pct <= max_percent
        ORDER BY min_percent DESC
        LIMIT 1;

        IF v_grade IS NULL THEN
            v_grade := CASE WHEN v_has_failed THEN 'F' ELSE 'C' END;
        END IF;

        IF v_has_failed THEN
            v_status := 'FAIL';
            v_fail_count := v_fail_count + 1;
        ELSE
            v_status := 'PASS';
            v_pass_count := v_pass_count + 1;
        END IF;

        -- Upsert into results with period_type and period_no
        INSERT INTO results (
            exam_id, student_id, total_marks, percentage, grade, status,
            period_type, period_no,
            created_at, updated_at, deleted_at, deleted_by
        )
        VALUES (
            p_exam_id, v_student.student_id, v_total_obtained, v_pct, v_grade, v_status,
            v_exam.period_type, v_exam.period_no,
            clock_timestamp(), clock_timestamp(), NULL, NULL
        )
        ON CONFLICT (exam_id, student_id)
        DO UPDATE SET
            total_marks = EXCLUDED.total_marks,
            percentage = EXCLUDED.percentage,
            grade = EXCLUDED.grade,
            status = EXCLUDED.status,
            period_type = EXCLUDED.period_type,
            period_no = EXCLUDED.period_no,
            deleted_at = NULL,
            deleted_by = NULL,
            updated_at = clock_timestamp();

        v_computed_count := v_computed_count + 1;
    END LOOP;

    -- Compute and assign academic rank among PASS students
    WITH ranked AS (
        SELECT id, rank() OVER (ORDER BY total_marks DESC) as rk
        FROM results
        WHERE exam_id = p_exam_id AND status = 'PASS' AND deleted_at IS NULL
    )
    UPDATE results r
    SET rank = ranked.rk,
        updated_at = clock_timestamp()
    FROM ranked
    WHERE r.id = ranked.id;

    RETURN jsonb_build_object(
        'success', true,
        'computed_students', v_computed_count,
        'passed', v_pass_count,
        'failed', v_fail_count
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


