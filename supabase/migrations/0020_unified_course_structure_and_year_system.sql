-- Trigger: Non-overlapping periods per batch and period_type
CREATE OR REPLACE FUNCTION check_batch_period_non_overlapping()
RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM batch_periods
        WHERE batch_id = NEW.batch_id
          AND period_type = NEW.period_type
          AND id != coalesce(NEW.id, -1)
          AND daterange(start_date, coalesce(end_date, '9999-12-31'::date), '[]') &&
              daterange(NEW.start_date, coalesce(NEW.end_date, '9999-12-31'::date), '[]')
    ) THEN
        RAISE EXCEPTION '% date range [% to %] overlaps with an existing % for batch %.',
            initcap(NEW.period_type), NEW.start_date, coalesce(NEW.end_date::text, 'ongoing'), NEW.period_type, NEW.batch_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

