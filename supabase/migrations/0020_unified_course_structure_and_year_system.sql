-- Period Assignment Trigger on attendance_sessions
CREATE OR REPLACE FUNCTION assign_attendance_session_period()
RETURNS TRIGGER AS $$
DECLARE
    v_basis text;
    v_period_type text;
    v_period_no int;
BEGIN
    SELECT coalesce(c.attendance_basis, c.structure, 'semester')
    INTO v_basis
    FROM batches b
    JOIN courses c ON c.id = b.course_id
    WHERE b.id = NEW.batch_id;

    IF v_basis = 'none' THEN
        NEW.period_type := 'semester';
        NEW.period_no := NULL;
        NEW.semester_no := NULL;
        RETURN NEW;
    END IF;

    v_period_type := v_basis;

    -- 1. Date window match in batch_periods
    SELECT period_no INTO v_period_no
    FROM batch_periods
    WHERE batch_id = NEW.batch_id
      AND period_type = v_period_type
      AND start_date <= NEW.date
      AND (end_date IS NULL OR end_date >= NEW.date)
    ORDER BY period_no DESC
    LIMIT 1;

    -- 2. Active status match in batch_periods
    IF v_period_no IS NULL THEN
        SELECT period_no INTO v_period_no
        FROM batch_periods
        WHERE batch_id = NEW.batch_id
          AND period_type = v_period_type
          AND status = 'active'
        ORDER BY period_no DESC
        LIMIT 1;
    END IF;

    -- 3. Fallback to current batch counter
    IF v_period_no IS NULL THEN
        IF v_period_type = 'year' THEN
            SELECT current_year INTO v_period_no FROM batches WHERE id = NEW.batch_id;
        ELSE
            SELECT current_semester INTO v_period_no FROM batches WHERE id = NEW.batch_id;
        END IF;
    END IF;

    NEW.period_type := v_period_type;
    NEW.period_no := coalesce(v_period_no, 1);
    IF v_period_type = 'semester' THEN
        NEW.semester_no := NEW.period_no;
    ELSE
        NEW.semester_no := NEW.period_no * 2;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql
SET search_path = public, pg_temp;

