-- 13. RECONCILIATION & AUDIT FUNCTION
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION get_migration_reconciliation_report()
RETURNS jsonb AS $$
DECLARE
    v_report jsonb;
    v_unparsed_exams jsonb;
BEGIN
    SELECT coalesce(jsonb_agg(jsonb_build_object(
        'id', id,
        'name', name,
        'course_id', course_id,
        'batch_id', batch_id,
        'raw_semester_text', semester
    )), '[]'::jsonb)
    INTO v_unparsed_exams
    FROM exams
    WHERE period_no IS NULL AND deleted_at IS NULL;

    SELECT jsonb_build_object(
        'courses_count', (SELECT count(*) FROM courses WHERE deleted_at IS NULL),
        'course_subjects_count', (SELECT count(*) FROM course_subjects WHERE deleted_at IS NULL),
        'batches_count', (SELECT count(*) FROM batches WHERE deleted_at IS NULL),
        'batch_periods_count', (SELECT count(*) FROM batch_periods),
        'exams_total', (SELECT count(*) FROM exams WHERE deleted_at IS NULL),
        'exams_parsed_period', (SELECT count(*) FROM exams WHERE period_no IS NOT NULL AND deleted_at IS NULL),
        'exams_unparsed_period', (SELECT count(*) FROM exams WHERE period_no IS NULL AND deleted_at IS NULL),
        'unparsed_exams_list', v_unparsed_exams,
        'results_count', (SELECT count(*) FROM results WHERE deleted_at IS NULL),
        'attendance_sessions_count', (SELECT count(*) FROM attendance_sessions),
        'timestamp', clock_timestamp()
    ) INTO v_report;

    RETURN v_report;
END;
$$ LANGUAGE plpgsql STABLE SECURITY DEFINER;
