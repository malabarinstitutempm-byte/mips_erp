-- Trigger to keep current_semester and current_year synchronized based on course structure
CREATE OR REPLACE FUNCTION sync_batch_periods()
RETURNS TRIGGER AS $$
DECLARE
    v_structure text;
BEGIN
    SELECT coalesce(structure, 'semester') INTO v_structure FROM courses WHERE id = NEW.course_id;
    
    IF v_structure = 'year' THEN
        -- For year-wise courses: current_year is primary
        NEW.current_year := coalesce(NEW.current_year, 1);
        NEW.current_semester := NEW.current_year * 2;
    ELSE
        -- For semester-wise courses (default): current_semester is primary
        NEW.current_semester := coalesce(NEW.current_semester, 1);
        NEW.current_year := ceil(NEW.current_semester::numeric / 2.0)::int;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql
SET search_path = public, pg_temp;

