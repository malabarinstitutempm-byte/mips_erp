-- Phase 10B/10C: Day-by-Day Daily Timetable Architecture & RLS Safeguards

-- 1. daily_timetables: Track publication state per day
-- Drop empty legacy prototype tables if present
DROP TABLE IF EXISTS daily_timetable_entries CASCADE;
DROP TABLE IF EXISTS daily_timetables CASCADE;

CREATE TABLE daily_timetables (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date NOT NULL UNIQUE,
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published', 'not_created')),
    published_at timestamptz,
    notify_users boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- 2. daily_timetable_entries: Scheduled class rows for each day
CREATE TABLE daily_timetable_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_timetable_id bigint REFERENCES daily_timetables(id) ON DELETE CASCADE,
    date date NOT NULL,
    course_id bigint REFERENCES courses(id) ON DELETE SET NULL,
    course_name text NOT NULL,
    year text NOT NULL DEFAULT '1st Year',
    teacher_id bigint REFERENCES teachers(id) ON DELETE SET NULL,
    teacher_name text NOT NULL,
    subject_id bigint REFERENCES course_subjects(id) ON DELETE SET NULL,
    subject_name text NOT NULL,
    class_room text NOT NULL,
    start_time text NOT NULL,
    end_time text NOT NULL,
    sort_order int DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS idx_daily_timetables_date ON daily_timetables (date, status);
CREATE INDEX IF NOT EXISTS idx_daily_timetable_entries_date ON daily_timetable_entries (date);
CREATE INDEX IF NOT EXISTS idx_daily_timetable_entries_teacher ON daily_timetable_entries (teacher_name, date);

-- 3. RLS Policies
ALTER TABLE daily_timetables ENABLE ROW LEVEL SECURITY;
ALTER TABLE daily_timetable_entries ENABLE ROW LEVEL SECURITY;

-- Admin Policy: Full Access
DROP POLICY IF EXISTS "Admins have full access to daily_timetables" ON daily_timetables;
CREATE POLICY "Admins have full access to daily_timetables"
ON daily_timetables FOR ALL
TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM profiles 
        WHERE profiles.user_id = auth.uid() 
          AND profiles.role = 'admin' 
          AND profiles.active = true
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1 FROM profiles 
        WHERE profiles.user_id = auth.uid() 
          AND profiles.role = 'admin' 
          AND profiles.active = true
    )
);

DROP POLICY IF EXISTS "Admins have full access to daily_timetable_entries" ON daily_timetable_entries;
CREATE POLICY "Admins have full access to daily_timetable_entries"
ON daily_timetable_entries FOR ALL
TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM profiles 
        WHERE profiles.user_id = auth.uid() 
          AND profiles.role = 'admin' 
          AND profiles.active = true
    )
)
WITH CHECK (
    EXISTS (
        SELECT 1 FROM profiles 
        WHERE profiles.user_id = auth.uid() 
          AND profiles.role = 'admin' 
          AND profiles.active = true
    )
);

-- Students & Teachers Read Policy:
-- Can ONLY read PUBLISHED days whose date is today or tomorrow (Asia/Kolkata timezone)
DROP POLICY IF EXISTS "Students and teachers can read published today and tomorrow daily_timetables" ON daily_timetables;
CREATE POLICY "Students and teachers can read published today and tomorrow daily_timetables"
ON daily_timetables FOR SELECT
TO authenticated
USING (
    status = 'published' AND
    date >= (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata')::date AND
    date <= ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata')::date + 1)
);

DROP POLICY IF EXISTS "Students and teachers can read published today and tomorrow daily_timetable_entries" ON daily_timetable_entries;
CREATE POLICY "Students and teachers can read published today and tomorrow daily_timetable_entries"
ON daily_timetable_entries FOR SELECT
TO authenticated
USING (
    EXISTS (
        SELECT 1 FROM daily_timetables dt
        WHERE dt.date = daily_timetable_entries.date
          AND dt.status = 'published'
          AND dt.date >= (CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata')::date
          AND dt.date <= ((CURRENT_TIMESTAMP AT TIME ZONE 'Asia/Kolkata')::date + 1)
    )
);

