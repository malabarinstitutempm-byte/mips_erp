CREATE OR REPLACE FUNCTION course_duration_years(p_course_id bigint)
RETURNS int AS $$
DECLARE
    v_dur text;
    v_years int;
BEGIN
    SELECT duration INTO v_dur FROM courses WHERE id = p_course_id;
    IF v_dur IS NULL THEN RETURN 2; END IF;
    v_years := coalesce(substring(v_dur from '[0-9]+')::int, 2);
    RETURN GREATEST(1, v_years);
END;
$$ LANGUAGE plpgsql STABLE;

