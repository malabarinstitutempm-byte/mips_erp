-- 3. batch_semesters: Semester Date Ranges & Status per Batch
-- =============================================================================
CREATE TABLE IF NOT EXISTS batch_semesters (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id bigint NOT NULL REFERENCES batches(id) ON DELETE CASCADE,
    semester_no int NOT NULL CHECK (semester_no >= 1),
    start_date date NOT NULL,
    end_date date,
    status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'closed')),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uk_batch_semester UNIQUE (batch_id, semester_no),
    CONSTRAINT chk_semester_dates CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE INDEX IF NOT EXISTS idx_batch_semesters_lookup 
    ON batch_semesters (batch_id, semester_no, status);

-- Trigger: Ensure non-overlapping semester dates per batch
CREATE OR REPLACE FUNCTION check_batch_semester_non_overlapping()
RETURNS TRIGGER AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM batch_semesters
        WHERE batch_id = NEW.batch_id
          AND id != coalesce(NEW.id, -1)
          AND daterange(start_date, coalesce(end_date, '9999-12-31'::date), '[]') &&
              daterange(NEW.start_date, coalesce(NEW.end_date, '9999-12-31'::date), '[]')
    ) THEN
        RAISE EXCEPTION 'Semester date range [% to %] overlaps with an existing semester for batch %.',
            NEW.start_date, coalesce(NEW.end_date::text, 'ongoing'), NEW.batch_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_check_batch_semester_dates ON batch_semesters;
CREATE TRIGGER trg_check_batch_semester_dates
    BEFORE INSERT OR UPDATE OF start_date, end_date ON batch_semesters
    FOR EACH ROW EXECUTE FUNCTION check_batch_semester_non_overlapping();

ALTER TABLE batch_semesters ENABLE ROW LEVEL SECURITY;

CREATE POLICY p_batch_semesters_all ON batch_semesters
    FOR ALL TO authenticated
    USING (true)
    WITH CHECK (
        EXISTS (
            SELECT 1 FROM profiles 
            WHERE profiles.id = auth.uid() AND profiles.role = 'admin' AND profiles.active = true
        )
    );

