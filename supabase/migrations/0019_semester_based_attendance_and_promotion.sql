CREATE OR REPLACE FUNCTION admin_update_session_semester(
    p_session_id bigint,
    p_new_semester_no int,
    p_reason text
)
RETURNS jsonb AS $$
DECLARE
    v_s RECORD;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM profiles 
        WHERE profiles.id = auth.uid() AND profiles.role = 'admin' AND profiles.active = true
    ) THEN
        RAISE EXCEPTION 'Access denied. Only administrators can alter session semester mappings.';
    END IF;

    IF p_reason IS NULL OR trim(p_reason) = '' THEN
        RAISE EXCEPTION 'A valid explanation reason is mandatory for altering session semester assignments.';
    END IF;

    SELECT * INTO v_s FROM attendance_sessions WHERE id = p_session_id;
    IF v_s.id IS NULL THEN
        RAISE EXCEPTION 'Session % not found.', p_session_id;
    END IF;

    UPDATE attendance_sessions
    SET semester_no = p_new_semester_no
    WHERE id = p_session_id;

    INSERT INTO audit_log (table_name, record_id, action, old_data, new_data, actor, created_at)
    VALUES (
        'attendance_sessions',
        p_session_id::text,
        'UPDATE_SESSION_SEMESTER',
        jsonb_build_object('old_semester', v_s.semester_no),
        jsonb_build_object('new_semester', p_new_semester_no, 'reason', p_reason),
        auth.uid(),
        clock_timestamp()
    );

    RETURN jsonb_build_object('success', true, 'session_id', p_session_id, 'new_semester', p_new_semester_no);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

