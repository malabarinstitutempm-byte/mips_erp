CREATE OR REPLACE FUNCTION admin_update_batch_semester_dates(
    p_batch_id bigint,
    p_semester_no int,
    p_start_date date,
    p_end_date date,
    p_reason text
)
RETURNS jsonb AS $$
DECLARE
    v_old RECORD;
    v_sessions_outside int := 0;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM profiles 
        WHERE profiles.id = auth.uid() AND profiles.role = 'admin' AND profiles.active = true
    ) THEN
        RAISE EXCEPTION 'Access denied. Only administrators can modify semester dates.';
    END IF;

    IF p_end_date IS NOT NULL AND p_end_date < p_start_date THEN
        RAISE EXCEPTION 'End date (%) cannot be earlier than start date (%).', p_end_date, p_start_date;
    END IF;

    SELECT * INTO v_old FROM batch_semesters 
    WHERE batch_id = p_batch_id AND semester_no = p_semester_no;

    IF v_old.id IS NULL THEN
        RAISE EXCEPTION 'Semester % for batch % does not exist.', p_semester_no, p_batch_id;
    END IF;

    -- Check if existing attendance sessions fall outside the new date boundaries
    SELECT count(*)::int INTO v_sessions_outside
    FROM attendance_sessions
    WHERE batch_id = p_batch_id 
      AND semester_no = p_semester_no
      AND (date < p_start_date OR (p_end_date IS NOT NULL AND date > p_end_date));

    IF v_sessions_outside > 0 AND (p_reason IS NULL OR trim(p_reason) = '') THEN
        RAISE EXCEPTION 'There are % attendance sessions falling outside the updated date range. A mandatory explanation reason is required.',
            v_sessions_outside;
    END IF;

    UPDATE batch_semesters
    SET start_date = p_start_date,
        end_date = p_end_date,
        updated_at = clock_timestamp()
    WHERE id = v_old.id;

    INSERT INTO audit_log (table_name, record_id, action, old_data, new_data, actor, created_at)
    VALUES (
        'batch_semesters',
        v_old.id::text,
        'UPDATE_SEMESTER_DATES',
        to_jsonb(v_old),
        jsonb_build_object('start_date', p_start_date, 'end_date', p_end_date, 'reason', p_reason),
        auth.uid(),
        clock_timestamp()
    );

    RETURN jsonb_build_object('success', true, 'affected_sessions', v_sessions_outside);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

