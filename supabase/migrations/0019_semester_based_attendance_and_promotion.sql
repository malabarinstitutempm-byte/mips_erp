CREATE OR REPLACE FUNCTION student_attendance_summary(
    p_student_id bigint, 
    p_enrollment_id bigint DEFAULT NULL,
    p_semester_no int DEFAULT NULL
)
RETURNS TABLE (
    student_id bigint,
    enrollment_id bigint,
    semester_no int,
    sessions_held int,
    present_count int,
    late_count int,
    absent_count int,
    leave_count int,
    weighted_present numeric(10,2),
    percentage numeric(5,2),
    status_band text,
    can_miss_more int,
    recover_sessions int,
    absent_impact_pct numeric(5,2),
    late_impact_pct numeric(5,2)
) AS $$
DECLARE
    v_enr_id bigint;
    v_batch_id bigint;
    v_enrolled_on date;
    v_target_sem int;
    v_sem_start date;
    v_sem_end date;
    v_min_pct numeric := 75.0;
    v_rem_pct numeric := 80.0;
    v_late_wt numeric := 0.5;
    v_leave_mode text := 'excluded';
    v_setting text;

    v_total_held int := 0;
    v_present int := 0;
    v_late int := 0;
    v_absent int := 0;
    v_leave int := 0;
    v_effective_held int := 0;
    v_weighted numeric(10,2) := 0.0;
    v_pct numeric(5,2) := 100.0;
    v_band text := 'ok';
    v_miss int := 0;
    v_recover int := 0;
    v_absent_impact numeric(5,2) := 0.0;
    v_late_impact numeric(5,2) := 0.0;
BEGIN
    IF is_student() AND p_student_id != current_student_id() THEN
        RAISE EXCEPTION 'Access denied. You can only view your own attendance summary.';
    END IF;

    SELECT value INTO v_setting FROM settings WHERE key = 'min_attendance_percent';
    IF v_setting IS NOT NULL THEN v_min_pct := v_setting::numeric; END IF;

    SELECT value INTO v_setting FROM settings WHERE key = 'reminder_attendance_percent';
    IF v_setting IS NOT NULL THEN v_rem_pct := v_setting::numeric; END IF;

    SELECT value INTO v_setting FROM settings WHERE key = 'late_weight';
    IF v_setting IS NOT NULL THEN v_late_wt := v_setting::numeric; END IF;

    SELECT value INTO v_setting FROM settings WHERE key = 'leave_handling';
    IF v_setting IS NOT NULL THEN v_leave_mode := lower(trim(v_setting)); END IF;

    -- Resolve student's PRIMARY enrollment
    SELECT se.id, se.batch_id, se.enrolled_on, b.current_semester
    INTO v_enr_id, v_batch_id, v_enrolled_on, v_target_sem
    FROM student_enrollments se
    JOIN batches b ON b.id = se.batch_id
    JOIN courses c ON c.id = b.course_id
    WHERE se.student_id = p_student_id 
      AND (se.kind = 'primary' OR c.course_type = 'primary')
      AND se.status = 'active'
      AND se.deleted_at IS NULL
    ORDER BY se.id DESC LIMIT 1;

    IF v_batch_id IS NULL THEN
        SELECT s.batch_id, coalesce(s.admission_date, CURRENT_DATE), b.current_semester
        INTO v_batch_id, v_enrolled_on, v_target_sem
        FROM students s
        JOIN batches b ON b.id = s.batch_id
        JOIN courses c ON c.id = b.course_id
        WHERE s.id = p_student_id AND c.course_type = 'primary';
    END IF;

    IF v_batch_id IS NULL THEN RETURN; END IF;

    -- Default semester to batch current_semester
    IF p_semester_no IS NOT NULL THEN
        v_target_sem := p_semester_no;
    END IF;

    -- Get semester date boundaries
    SELECT start_date, end_date INTO v_sem_start, v_sem_end
    FROM batch_semesters
    WHERE batch_id = v_batch_id AND semester_no = v_target_sem;

    IF v_sem_start IS NULL THEN
        v_sem_start := v_enrolled_on;
    END IF;

    -- Total sessions held in this semester
    SELECT count(*)::int INTO v_total_held
    FROM attendance_sessions s
    JOIN batches b ON b.id = s.batch_id
    JOIN courses c ON c.id = b.course_id
    WHERE s.batch_id = v_batch_id
      AND c.course_type = 'primary'
      AND (s.semester_no = v_target_sem OR (s.date >= v_sem_start AND (v_sem_end IS NULL OR s.date <= v_sem_end)))
      AND s.date >= v_enrolled_on
      AND s.status IN ('submitted', 'locked');

    -- Tally student attendance records for this semester
    SELECT 
        count(*) FILTER (WHERE ar.status = 'present')::int,
        count(*) FILTER (WHERE ar.status = 'late')::int,
        count(*) FILTER (WHERE ar.status = 'absent')::int,
        count(*) FILTER (WHERE ar.status = 'leave')::int
    INTO v_present, v_late, v_absent, v_leave
    FROM attendance_records ar
    JOIN attendance_sessions s ON s.id = ar.session_id
    JOIN batches b ON b.id = s.batch_id
    JOIN courses c ON c.id = b.course_id
    WHERE ar.student_id = p_student_id
      AND s.batch_id = v_batch_id
      AND c.course_type = 'primary'
      AND (s.semester_no = v_target_sem OR (s.date >= v_sem_start AND (v_sem_end IS NULL OR s.date <= v_sem_end)))
      AND s.date >= v_enrolled_on
      AND s.status IN ('submitted', 'locked');

    -- Effective sessions
    IF v_leave_mode = 'counted_present' THEN
        v_effective_held := v_total_held;
        v_weighted := v_present + v_leave + (v_late * v_late_wt);
    ELSIF v_leave_mode = 'counted_absent' THEN
        v_effective_held := v_total_held;
        v_weighted := v_present + (v_late * v_late_wt);
    ELSE
        v_effective_held := GREATEST(0, v_total_held - v_leave);
        v_weighted := v_present + (v_late * v_late_wt);
    END IF;

    IF v_effective_held > 0 THEN
        v_pct := round((v_weighted / v_effective_held::numeric) * 100.0, 2);
    ELSE
        v_pct := 100.0;
    END IF;

    -- Band determination
    IF v_pct < v_min_pct THEN
        v_band := 'shortage';
    ELSIF v_pct < v_rem_pct THEN
        v_band := 'low';
    ELSE
        v_band := 'ok';
    END IF;

    -- can_miss_more & recover_sessions (Current semester only)
    IF v_effective_held > 0 THEN
        IF v_pct >= v_min_pct THEN
            v_miss := floor((v_weighted - (v_min_pct / 100.0) * v_effective_held) / (v_min_pct / 100.0))::int;
            v_miss := GREATEST(0, v_miss);
            v_recover := 0;
        ELSE
            v_miss := 0;
            v_recover := ceil(((v_min_pct / 100.0) * v_effective_held - v_weighted) / (1.0 - (v_min_pct / 100.0)))::int;
            v_recover := GREATEST(1, v_recover);
        END IF;

        v_absent_impact := round((1.0 / (v_effective_held + 1)::numeric) * 100.0, 2);
        v_late_impact := round(((1.0 - v_late_wt) / (v_effective_held + 1)::numeric) * 100.0, 2);
    END IF;

    RETURN QUERY SELECT
        p_student_id,
        v_enr_id,
        v_target_sem,
        v_effective_held,
        v_present,
        v_late,
        v_absent,
        v_leave,
        v_weighted,
        v_pct,
        v_band,
        v_miss,
        v_recover,
        v_absent_impact,
        v_late_impact;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER STABLE
SET search_path = public, pg_temp;

-- =============================================================================
-- 8. student_semesters_summary: All Semesters for a Student
-- =============================================================================
CREATE OR REPLACE FUNCTION student_semesters_summary(
    p_student_id bigint,
    p_enrollment_id bigint DEFAULT NULL
)
RETURNS TABLE (
    semester_no int,
    year_no int,
    start_date date,
    end_date date,
    status text,
    sessions_held int,
    present_count int,
    late_count int,
    absent_count int,
    leave_count int,
    percentage numeric(5,2),
    status_band text,
    met_minimum boolean,
    is_current boolean
) AS $$
DECLARE
    v_batch_id bigint;
    v_curr_sem int;
    r RECORD;
    v_sum RECORD;
BEGIN
    SELECT b.id, b.current_semester INTO v_batch_id, v_curr_sem
    FROM students s
    JOIN batches b ON b.id = s.batch_id
    WHERE s.id = p_student_id;

    IF v_batch_id IS NULL THEN RETURN; END IF;

    FOR r IN (
        SELECT bs.semester_no, bs.start_date, bs.end_date, bs.status
        FROM batch_semesters bs
        WHERE bs.batch_id = v_batch_id
        ORDER BY bs.semester_no ASC
    ) LOOP
        SELECT * INTO v_sum 
        FROM student_attendance_summary(p_student_id, p_enrollment_id, r.semester_no);

        semester_no := r.semester_no;
        year_no := ceil(r.semester_no::numeric / 2.0)::int;
        start_date := r.start_date;
        end_date := r.end_date;
        status := r.status;
        sessions_held := coalesce(v_sum.sessions_held, 0);
        present_count := coalesce(v_sum.present_count, 0);
        late_count := coalesce(v_sum.late_count, 0);
        absent_count := coalesce(v_sum.absent_count, 0);
        leave_count := coalesce(v_sum.leave_count, 0);
        percentage := coalesce(v_sum.percentage, 100.0);
        status_band := coalesce(v_sum.status_band, 'ok');
        met_minimum := (percentage >= 75.0);
        is_current := (r.semester_no = v_curr_sem);
        RETURN NEXT;
    END LOOP;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER STABLE
SET search_path = public, pg_temp;

-- =============================================================================
-- 9. evaluate_attendance_bands: Current Semester Only
-- =============================================================================
CREATE OR REPLACE FUNCTION evaluate_attendance_bands(
    p_student_id bigint DEFAULT NULL,
    p_batch_id bigint DEFAULT NULL
)
RETURNS jsonb AS $$
DECLARE
    v_target_students bigint[];
    v_sid bigint;
    v_summary RECORD;
    v_last_band text;
    v_alerts_sent int := 0;
    v_student_name text;
    v_adm_no text;
    v_enr_id bigint;
    v_admin_user_id uuid;
    v_curr_sem int;
BEGIN
    IF p_student_id IS NOT NULL THEN
        SELECT ARRAY[id] INTO v_target_students
        FROM students
        WHERE id = p_student_id AND status = 'active' AND deleted_at IS NULL;
        IF v_target_students IS NULL THEN
            RETURN jsonb_build_object('success', true, 'alerts_sent', 0, 'message', 'Student is not active.');
        END IF;
    ELSIF p_batch_id IS NOT NULL THEN
        SELECT coalesce(array_agg(s.id), ARRAY[]::bigint[])
        INTO v_target_students
        FROM students s
        JOIN student_enrollments se ON se.student_id = s.id AND se.batch_id = p_batch_id AND se.status = 'active'
        WHERE s.status = 'active' AND s.deleted_at IS NULL;
    ELSE
        RETURN jsonb_build_object('success', false, 'message', 'Either student_id or batch_id must be provided.');
    END IF;

    FOREACH v_sid IN ARRAY v_target_students
    LOOP
        -- student_attendance_summary defaults to the batch's current semester
        SELECT * INTO v_summary FROM student_attendance_summary(v_sid) LIMIT 1;

        IF v_summary.student_id IS NOT NULL THEN
            v_enr_id := coalesce(v_summary.enrollment_id, 0);
            v_curr_sem := coalesce(v_summary.semester_no, 1);

            SELECT last_band INTO v_last_band
            FROM attendance_alert_state
            WHERE student_id = v_sid AND enrollment_id = v_enr_id AND semester_no = v_curr_sem;

            IF v_last_band IS NULL THEN
                v_last_band := 'ok';
            END IF;

            IF v_summary.status_band != v_last_band THEN
                SELECT name, admission_number INTO v_student_name, v_adm_no
                FROM students WHERE id = v_sid;

                IF v_summary.status_band = 'low' THEN
                    INSERT INTO notifications (
                        recipient_type, recipient_id, type, title, body, created_at
                    ) VALUES (
                        'student', v_sid, 'attendance_warning', 'Low attendance',
                        format('Your Semester %s attendance is currently %s%%. You can miss at most %s more session(s) before facing a shortage below 75%%.', 
                               v_curr_sem, v_summary.percentage, v_summary.can_miss_more),
                        clock_timestamp()
                    );
                    v_alerts_sent := v_alerts_sent + 1;

                ELSIF v_summary.status_band = 'shortage' THEN
                    INSERT INTO notifications (
                        recipient_type, recipient_id, type, title, body, created_at
                    ) VALUES (
                        'student', v_sid, 'attendance_shortage', 'Attendance shortage',
                        format('Your Semester %s attendance is currently %s%% (below 75%%). You must attend the next %s consecutive session(s) to regain eligibility.', 
                               v_curr_sem, v_summary.percentage, v_summary.recover_sessions),
                        clock_timestamp()
                    );

                    SELECT user_id INTO v_admin_user_id FROM profiles WHERE role = 'admin' AND active = true LIMIT 1;
                    IF v_admin_user_id IS NOT NULL THEN
                        INSERT INTO notifications (
                            user_id, recipient_type, recipient_id, type, title, body, created_at
                        ) VALUES (
                            v_admin_user_id, 'admin', NULL, 'student_attendance_shortage',
                            format('Attendance shortage: %s', v_student_name),
                            format('%s (%s) has an attendance shortage of %s%% in Semester %s.', v_student_name, v_adm_no, v_summary.percentage, v_curr_sem),
                            clock_timestamp()
                        );
                    END IF;
                    v_alerts_sent := v_alerts_sent + 1;
                END IF;

                INSERT INTO attendance_alert_state (
                    student_id, enrollment_id, semester_no, last_band, updated_at
                ) VALUES (
                    v_sid, v_enr_id, v_curr_sem, v_summary.status_band, clock_timestamp()
                )
                ON CONFLICT (student_id, enrollment_id, semester_no)
                DO UPDATE SET
                    last_band = EXCLUDED.last_band,
                    updated_at = EXCLUDED.updated_at;
            END IF;
        END IF;
    END LOOP;

    RETURN jsonb_build_object('success', true, 'alerts_sent', v_alerts_sent);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- =============================================================================
-- 10. preview_semester_promotion(batch_id) & promote_semester(...)
-- =============================================================================
CREATE OR REPLACE FUNCTION preview_semester_promotion(p_batch_id bigint)
RETURNS jsonb AS $$
DECLARE
    v_b RECORD;
    v_dur_years int;
    v_max_sem int;
    v_students jsonb;
    v_below_count int := 0;
    v_total_count int := 0;
BEGIN
    SELECT b.*, c.name AS course_name, c.id AS c_id
    INTO v_b
    FROM batches b
    JOIN courses c ON c.id = b.course_id
    WHERE b.id = p_batch_id AND b.deleted_at IS NULL;

    IF v_b.id IS NULL THEN
        RAISE EXCEPTION 'Batch % not found.', p_batch_id;
    END IF;

    v_dur_years := course_duration_years(v_b.c_id);
    v_max_sem := v_dur_years * 2;

    WITH batch_studs AS (
        SELECT s.id, s.name, s.admission_number, s.registration_number, se.id AS enr_id
        FROM students s
        JOIN student_enrollments se ON se.student_id = s.id AND se.batch_id = p_batch_id AND se.status = 'active'
        WHERE s.status = 'active' AND s.deleted_at IS NULL
    ),
    stud_summaries AS (
        SELECT 
            bs.id AS student_id,
            bs.name,
            bs.admission_number,
            bs.registration_number,
            coalesce(att.sessions_held, 0) AS sessions_held,
            coalesce(att.present_count + att.late_count, 0) AS attended_count,
            coalesce(att.percentage, 100.0) AS attendance_percentage,
            coalesce(att.status_band, 'ok') AS status_band,
            (coalesce(att.percentage, 100.0) < 75.0) AS below_minimum
        FROM batch_studs bs
        LEFT JOIN LATERAL (
            SELECT sas.* FROM student_attendance_summary(bs.id, bs.enr_id, v_b.current_semester) sas
            LIMIT 1
        ) att ON true
    )
    SELECT 
        coalesce(jsonb_agg(to_jsonb(ss)), '[]'::jsonb),
        count(*)::int,
        count(*) FILTER (WHERE ss.below_minimum)::int
    INTO v_students, v_total_count, v_below_count
    FROM stud_summaries ss;

    RETURN jsonb_build_object(
        'batch_id', v_b.id,
        'batch_name', v_b.batch_name,
        'course_name', v_b.course_name,
        'current_semester', v_b.current_semester,
        'current_year', ceil(v_b.current_semester::numeric / 2.0)::int,
        'next_semester', v_b.current_semester + 1,
        'next_year', ceil((v_b.current_semester + 1)::numeric / 2.0)::int,
        'year_will_change', (ceil((v_b.current_semester + 1)::numeric / 2.0)::int > ceil(v_b.current_semester::numeric / 2.0)::int),
        'course_duration_years', v_dur_years,
        'max_semesters', v_max_sem,
        'is_final_semester', (v_b.current_semester >= v_max_sem),
        'total_students', v_total_count,
        'below_minimum_count', v_below_count,
        'students', v_students
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER STABLE;

CREATE OR REPLACE FUNCTION promote_semester(
    p_batch_id bigint,
    p_closing_end_date date,
    p_new_start_date date
)
RETURNS jsonb AS $$
DECLARE
    v_b RECORD;
    v_dur_years int;
    v_max_sem int;
    v_curr_sem int;
    v_next_sem int;
    v_next_year int;
    v_prev_sem_start date;
    v_s RECORD;
    v_att RECORD;
    v_promoted_count int := 0;
BEGIN
    -- Admin guard
    IF NOT EXISTS (
        SELECT 1 FROM profiles 
        WHERE profiles.id = auth.uid() AND profiles.role = 'admin' AND profiles.active = true
    ) THEN
        RAISE EXCEPTION 'Access denied. Only administrators can execute semester promotions.';
    END IF;

    SELECT b.*, c.id AS c_id, c.name AS course_name
    INTO v_b
    FROM batches b
    JOIN courses c ON c.id = b.course_id
    WHERE b.id = p_batch_id AND b.deleted_at IS NULL;

    IF v_b.id IS NULL THEN
        RAISE EXCEPTION 'Batch % not found.', p_batch_id;
    END IF;

    v_dur_years := course_duration_years(v_b.c_id);
    v_max_sem := v_dur_years * 2;
    v_curr_sem := v_b.current_semester;
    v_next_sem := v_curr_sem + 1;
    v_next_year := ceil(v_next_sem::numeric / 2.0)::int;

    IF v_curr_sem >= v_max_sem THEN
        RAISE EXCEPTION 'Batch "%" is already in its final semester (Semester %). Use "Mark batch completed" instead of promotion.',
            v_b.batch_name, v_curr_sem;
    END IF;

    -- Validate dates
    SELECT start_date INTO v_prev_sem_start 
    FROM batch_semesters 
    WHERE batch_id = p_batch_id AND semester_no = v_curr_sem;

    IF v_prev_sem_start IS NOT NULL AND p_closing_end_date < v_prev_sem_start THEN
        RAISE EXCEPTION 'Closing semester end date (%) cannot be earlier than its start date (%).',
            p_closing_end_date, v_prev_sem_start;
    END IF;

    IF p_new_start_date <= p_closing_end_date THEN
        RAISE EXCEPTION 'New semester start date (%) must be after closing semester end date (%).',
            p_new_start_date, p_closing_end_date;
    END IF;

    -- 1. Close current semester
    UPDATE batch_semesters
    SET end_date = p_closing_end_date,
        status = 'closed',
        updated_at = clock_timestamp()
    WHERE batch_id = p_batch_id AND semester_no = v_curr_sem;

    -- 2. Open next semester
    INSERT INTO batch_semesters (batch_id, semester_no, start_date, end_date, status)
    VALUES (p_batch_id, v_next_sem, p_new_start_date, NULL, 'active');

    -- 3. Advance batch current_semester
    UPDATE batches
    SET current_semester = v_next_sem,
        updated_at = clock_timestamp()
    WHERE id = p_batch_id;

    -- 4. Audit log
    INSERT INTO audit_log (table_name, record_id, action, old_data, new_data, actor, created_at)
    VALUES (
        'batches',
        p_batch_id::text,
        'SEMESTER_PROMOTION',
        jsonb_build_object('semester_no', v_curr_sem, 'end_date', p_closing_end_date),
        jsonb_build_object('semester_no', v_next_sem, 'start_date', p_new_start_date, 'year', v_next_year),
        auth.uid(),
        clock_timestamp()
    );

    -- 5. Notify each student of this batch with their closing attendance
    FOR v_s IN (
        SELECT s.id, s.name, se.id AS enr_id
        FROM students s
        JOIN student_enrollments se ON se.student_id = s.id AND se.batch_id = p_batch_id AND se.status = 'active'
        WHERE s.status = 'active' AND s.deleted_at IS NULL
    ) LOOP
        SELECT * INTO v_att FROM student_attendance_summary(v_s.id, v_s.enr_id, v_curr_sem);

        INSERT INTO notifications (
            recipient_type, recipient_id, type, title, body, created_at
        ) VALUES (
            'student',
            v_s.id,
            'semester_promotion',
            'Semester Promotion',
            format('You are now in Semester %s (Year %s). Your Semester %s attendance: %s%%.',
                   v_next_sem, v_next_year, v_curr_sem, coalesce(v_att.percentage, 100.0)),
            clock_timestamp()
        );
        v_promoted_count := v_promoted_count + 1;
    END LOOP;

    -- 6. Insert teacher announcement / notice
    INSERT INTO announcements (
        category, title, body, audience_type, audience_ids, created_by, created_at
    ) VALUES (
        'academic',
        format('Batch %s Promoted to Semester %s', v_b.batch_name, v_next_sem),
        format('Batch %s has successfully completed Semester %s and has advanced to Semester %s (Year %s).',
               v_b.batch_name, v_curr_sem, v_next_sem, v_next_year),
        'teachers',
        '[]'::jsonb,
        auth.uid(),
        clock_timestamp()
    );

    RETURN jsonb_build_object(
        'success', true,
        'batch_id', p_batch_id,
        'promoted_to_semester', v_next_sem,
        'promoted_to_year', v_next_year,
        'students_notified', v_promoted_count
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

