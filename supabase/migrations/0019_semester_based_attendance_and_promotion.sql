CREATE TRIGGER trg_attendance_sessions_assign_semester
    BEFORE INSERT OR UPDATE OF date, batch_id ON attendance_sessions
    FOR EACH ROW EXECUTE FUNCTION assign_attendance_session_semester();

-- =============================================================================
-- 5. Data Migration: Populate batch_semesters & Assign Existing Attendance
-- =============================================================================
DO $$
DECLARE
    r RECORD;
    v_initial_sem int;
    v_start date;
BEGIN
    FOR r IN SELECT * FROM batches WHERE deleted_at IS NULL LOOP
        v_start := coalesce(r.start_date, '2024-01-01'::date);
        v_initial_sem := coalesce(r.current_semester, 1);

        -- Insert initial semester if absent
        INSERT INTO batch_semesters (batch_id, semester_no, start_date, end_date, status)
        VALUES (r.id, v_initial_sem, v_start, NULL, 'active')
        ON CONFLICT (batch_id, semester_no) DO NOTHING;

        -- Assign existing attendance to this semester
        UPDATE attendance_sessions
        SET semester_no = v_initial_sem
        WHERE batch_id = r.id AND semester_no IS NULL;
    END LOOP;
END $$;

-- Check & log any batches where session dates precede semester start_date
CREATE OR REPLACE FUNCTION audit_inconsistent_batch_semester_dates()
RETURNS TABLE (
    batch_id bigint,
    batch_name text,
    semester_start date,
    earliest_session date,
    inconsistent_session_count int
) AS $$
BEGIN
    RETURN QUERY
    SELECT 
        b.id,
        b.batch_name,
        bs.start_date,
        min(s.date) AS earliest_session,
        count(s.id)::int AS inconsistent_session_count
    FROM batches b
    JOIN batch_semesters bs ON bs.batch_id = b.id AND bs.status = 'active'
    JOIN attendance_sessions s ON s.batch_id = b.id
    WHERE s.date < bs.start_date
    GROUP BY b.id, b.batch_name, bs.start_date;
END;
$$ LANGUAGE plpgsql STABLE;

