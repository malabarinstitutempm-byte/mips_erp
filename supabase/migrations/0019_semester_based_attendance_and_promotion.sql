CREATE OR REPLACE FUNCTION assign_attendance_session_semester()
RETURNS TRIGGER AS $$
DECLARE
    v_sem_no int;
BEGIN
    -- Resolve semester from batch_semesters based on session date
    SELECT semester_no INTO v_sem_no
    FROM batch_semesters
    WHERE batch_id = NEW.batch_id
      AND NEW.date >= start_date
      AND (end_date IS NULL OR NEW.date <= end_date)
    ORDER BY semester_no DESC
    LIMIT 1;

    IF v_sem_no IS NULL THEN
        RAISE EXCEPTION 'Session date % is outside any semester date range for batch %. Please configure semester dates in Batch Management.',
            NEW.date, NEW.batch_id;
    END IF;

    NEW.semester_no := v_sem_no;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

