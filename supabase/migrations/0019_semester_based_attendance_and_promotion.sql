CREATE OR REPLACE FUNCTION report_shortage(
    p_course_id bigint DEFAULT NULL,
    p_batch_id bigint DEFAULT NULL,
    p_semester_no int DEFAULT NULL,
    p_band text DEFAULT 'all'
)
RETURNS TABLE (
    student_id bigint,
    student_name text,
    admission_number text,
    registration_number text,
    course_name text,
    batch_name text,
    course_id bigint,
    batch_id bigint,
    semester_no int,
    year_no int,
    sessions_held int,
    present_count int,
    late_count int,
    absent_count int,
    leave_count int,
    percentage numeric(5,2),
    status_band text,
    can_miss_more int,
    recover_sessions int
) AS $$
BEGIN
    RETURN QUERY
    WITH active_studs AS (
        SELECT 
            s.id AS sid,
            s.name AS sname,
            s.admission_number AS sadm,
            s.registration_number AS sreg,
            c.name AS cname,
            b.batch_name AS bname,
            s.course_id AS cid,
            s.batch_id AS bid,
            b.current_semester AS b_curr_sem,
            se.id AS eid
        FROM students s
        JOIN courses c ON c.id = s.course_id
        JOIN batches b ON b.id = s.batch_id
        JOIN student_enrollments se ON se.student_id = s.id AND se.batch_id = b.id AND se.status = 'active'
        WHERE s.status = 'active'
          AND s.deleted_at IS NULL
          AND (p_course_id IS NULL OR s.course_id = p_course_id)
          AND (p_batch_id IS NULL OR s.batch_id = p_batch_id)
    )
    SELECT 
        ast.sid,
        ast.sname,
        ast.sadm,
        ast.sreg,
        ast.cname,
        ast.bname,
        ast.cid,
        ast.bid,
        coalesce(p_semester_no, ast.b_curr_sem) AS semester_no,
        ceil(coalesce(p_semester_no, ast.b_curr_sem)::numeric / 2.0)::int AS year_no,
        coalesce(att.sessions_held, 0),
        coalesce(att.present_count, 0),
        coalesce(att.late_count, 0),
        coalesce(att.absent_count, 0),
        coalesce(att.leave_count, 0),
        coalesce(att.percentage, 100.0),
        coalesce(att.status_band, 'ok'),
        coalesce(att.can_miss_more, 0),
        coalesce(att.recover_sessions, 0)
    FROM active_studs ast
    LEFT JOIN LATERAL (
        SELECT sas.* FROM student_attendance_summary(ast.sid, ast.eid, coalesce(p_semester_no, ast.b_curr_sem)) sas
        LIMIT 1
    ) att ON true
    WHERE p_band = 'all' OR coalesce(att.status_band, 'ok') = p_band;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER STABLE;

