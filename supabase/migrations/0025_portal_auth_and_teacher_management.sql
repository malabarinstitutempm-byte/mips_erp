-- 1. Table for persistent institutional portal passwords (synced across devices)
CREATE TABLE IF NOT EXISTS public.portal_credentials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role text NOT NULL CHECK (role IN ('student', 'teacher', 'admin')),
    identifier text NOT NULL,
    password_hash text NOT NULL,
    is_temporary boolean NOT NULL DEFAULT false,
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_portal_credentials UNIQUE (role, identifier)
);

CREATE INDEX IF NOT EXISTS idx_portal_credentials_lookup 
ON public.portal_credentials (lower(identifier), role);

GRANT SELECT, INSERT, UPDATE ON public.portal_credentials TO anon, authenticated, service_role;

-- 2. Master Portal Verification Function (SECURITY DEFINER for anon)
CREATE OR REPLACE FUNCTION public.portal_verify_login(
    p_identifier text,
    p_password text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_clean_id text := lower(trim(p_identifier));
    v_clean_pass text := trim(p_password);
    v_student record;
    v_teacher record;
    v_cred record;
    v_dob_iso text;
    v_dob_slash text;
    v_dob_dash text;
    v_dob_compact text;
    v_is_dob_match boolean := false;
    v_is_default_pass boolean := false;
    v_clean_phone text;
BEGIN
    IF v_clean_id IS NULL OR v_clean_id = '' OR v_clean_pass IS NULL OR v_clean_pass = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Register number or password is required.');
    END IF;

    -- A. Check Students Table
    SELECT s.id, s.name, s.admission_number, s.registration_number, s.dob, s.status, s.phone, s.email, s.course_id
    INTO v_student
    FROM public.students s
    WHERE (lower(s.admission_number) = v_clean_id OR (s.registration_number IS NOT NULL AND lower(s.registration_number) = v_clean_id))
      AND s.deleted_at IS NULL
    LIMIT 1;

    IF v_student.id IS NOT NULL THEN
        IF v_student.status::text IN ('discontinued', 'tc_issued') THEN
            RETURN jsonb_build_object('success', false, 'error', 'Your account has been deactivated. Please contact administration.');
        END IF;

        -- Check stored password in portal_credentials
        SELECT * INTO v_cred
        FROM public.portal_credentials
        WHERE role = 'student' AND lower(identifier) = v_clean_id;

        IF v_cred.id IS NOT NULL AND v_cred.password_hash = v_clean_pass THEN
            RETURN jsonb_build_object(
                'success', true,
                'role', 'student',
                'is_first_time', v_cred.is_temporary,
                'user', jsonb_build_object(
                    'id', 's_' || v_student.id,
                    'student_id', v_student.id,
                    'name', v_student.name,
                    'email', lower(coalesce(v_student.registration_number, v_student.admission_number)) || '@students.mips.invalid',
                    'identifier', coalesce(v_student.registration_number, v_student.admission_number),
                    'role', 'student'
                )
            );
        END IF;

        -- Check DOB match
        IF v_student.dob IS NOT NULL THEN
            v_dob_iso := to_char(v_student.dob, 'YYYY-MM-DD');
            v_dob_slash := to_char(v_student.dob, 'DD/MM/YYYY');
            v_dob_dash := to_char(v_student.dob, 'DD-MM-YYYY');
            v_dob_compact := to_char(v_student.dob, 'YYYYMMDD');

            IF v_clean_pass = v_dob_iso OR v_clean_pass = v_dob_slash OR v_clean_pass = v_dob_dash OR v_clean_pass = v_dob_compact THEN
                v_is_dob_match := true;
            END IF;
        END IF;

        -- Check standard institutional defaults
        IF v_clean_pass IN ('Student#Pass2026', 'student123', 'password123', 'Hi@1234567') THEN
            v_is_default_pass := true;
        END IF;

        IF v_is_dob_match OR v_is_default_pass THEN
            RETURN jsonb_build_object(
                'success', true,
                'role', 'student',
                'is_first_time', true,
                'user', jsonb_build_object(
                    'id', 's_' || v_student.id,
                    'student_id', v_student.id,
                    'name', v_student.name,
                    'email', lower(coalesce(v_student.registration_number, v_student.admission_number)) || '@students.mips.invalid',
                    'identifier', coalesce(v_student.registration_number, v_student.admission_number),
                    'role', 'student'
                )
            );
        ELSE
            RETURN jsonb_build_object('success', false, 'error', 'Register number or password is incorrect.');
        END IF;
    END IF;

    -- B. Check Teachers Table
    SELECT t.id, t.name, t.login_username, t.phone, t.status
    INTO v_teacher
    FROM public.teachers t
    WHERE lower(t.login_username) = v_clean_id
      AND t.deleted_at IS NULL
    LIMIT 1;

    IF v_teacher.id IS NOT NULL THEN
        IF v_teacher.status::text = 'inactive' THEN
            RETURN jsonb_build_object('success', false, 'error', 'Your account has been deactivated. Please contact administration.');
        END IF;

        -- Check stored password in portal_credentials
        SELECT * INTO v_cred
        FROM public.portal_credentials
        WHERE role = 'teacher' AND lower(identifier) = v_clean_id;

        IF v_cred.id IS NOT NULL AND v_cred.password_hash = v_clean_pass THEN
            RETURN jsonb_build_object(
                'success', true,
                'role', 'teacher',
                'is_first_time', v_cred.is_temporary,
                'user', jsonb_build_object(
                    'id', 't_' || v_teacher.id,
                    'teacher_id', v_teacher.id,
                    'name', v_teacher.name,
                    'email', lower(v_teacher.login_username) || '@teachers.mips.invalid',
                    'identifier', v_teacher.login_username,
                    'role', 'teacher'
                )
            );
        END IF;

        -- Check registered phone
        v_clean_phone := regexp_replace(coalesce(v_teacher.phone, ''), '[^0-9]', '', 'g');
        IF length(v_clean_phone) >= 10 AND (v_clean_pass = v_clean_phone OR v_clean_pass = right(v_clean_phone, 10)) THEN
            RETURN jsonb_build_object(
                'success', true,
                'role', 'teacher',
                'is_first_time', true,
                'user', jsonb_build_object(
                    'id', 't_' || v_teacher.id,
                    'teacher_id', v_teacher.id,
                    'name', v_teacher.name,
                    'email', lower(v_teacher.login_username) || '@teachers.mips.invalid',
                    'identifier', v_teacher.login_username,
                    'role', 'teacher'
                )
            );
        END IF;

        -- Check standard teacher defaults
        IF v_clean_pass IN ('Teacher#Pass2026', 'teacher123', 'admin123', 'password123', 'Hi@1234567') THEN
            RETURN jsonb_build_object(
                'success', true,
                'role', 'teacher',
                'is_first_time', true,
                'user', jsonb_build_object(
                    'id', 't_' || v_teacher.id,
                    'teacher_id', v_teacher.id,
                    'name', v_teacher.name,
                    'email', lower(v_teacher.login_username) || '@teachers.mips.invalid',
                    'identifier', v_teacher.login_username,
                    'role', 'teacher'
                )
            );
        ELSE
            RETURN jsonb_build_object('success', false, 'error', 'Register number or password is incorrect.');
        END IF;
    END IF;

    -- C. Not found
    RETURN jsonb_build_object('success', false, 'error', 'Register number or password is incorrect.');
END;
$$;

-- 3. First-Time Activation Function
CREATE OR REPLACE FUNCTION public.portal_first_login_verify(
    p_role text,
    p_identifier text,
    p_secret text,
    p_new_password text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_clean_id text := lower(trim(p_identifier));
    v_clean_sec text := trim(p_secret);
    v_student record;
    v_teacher record;
    v_dob_iso text;
    v_dob_slash text;
    v_dob_dash text;
    v_clean_phone text;
BEGIN
    IF p_role = 'student' THEN
        SELECT s.id, s.name, s.admission_number, s.registration_number, s.dob, s.status
        INTO v_student
        FROM public.students s
        WHERE (lower(s.admission_number) = v_clean_id OR (s.registration_number IS NOT NULL AND lower(s.registration_number) = v_clean_id))
          AND s.deleted_at IS NULL
        LIMIT 1;

        IF v_student.id IS NULL THEN
            RETURN jsonb_build_object('success', false, 'error', 'Student record not found in institutional records.');
        END IF;

        IF v_student.status::text IN ('discontinued', 'tc_issued') THEN
            RETURN jsonb_build_object('success', false, 'error', 'Your account has been deactivated. Please contact administration.');
        END IF;

        v_dob_iso := to_char(v_student.dob, 'YYYY-MM-DD');
        v_dob_slash := to_char(v_student.dob, 'DD/MM/YYYY');
        v_dob_dash := to_char(v_student.dob, 'DD-MM-YYYY');

        IF v_clean_sec != v_dob_iso AND v_clean_sec != v_dob_slash AND v_clean_sec != v_dob_dash THEN
            RETURN jsonb_build_object('success', false, 'error', 'Date of Birth does not match institutional records.');
        END IF;

        -- Save permanent password
        INSERT INTO public.portal_credentials (role, identifier, password_hash, is_temporary, updated_at)
        VALUES ('student', v_clean_id, p_new_password, false, clock_timestamp())
        ON CONFLICT (role, identifier) DO UPDATE
        SET password_hash = EXCLUDED.password_hash, is_temporary = false, updated_at = clock_timestamp();

        RETURN jsonb_build_object(
            'success', true,
            'role', 'student',
            'user', jsonb_build_object(
                'id', 's_' || v_student.id,
                'student_id', v_student.id,
                'name', v_student.name,
                'email', lower(coalesce(v_student.registration_number, v_student.admission_number)) || '@students.mips.invalid',
                'identifier', coalesce(v_student.registration_number, v_student.admission_number),
                'role', 'student'
            )
        );

    ELSIF p_role = 'teacher' THEN
        SELECT t.id, t.name, t.login_username, t.phone, t.status
        INTO v_teacher
        FROM public.teachers t
        WHERE lower(t.login_username) = v_clean_id
          AND t.deleted_at IS NULL
        LIMIT 1;

        IF v_teacher.id IS NULL THEN
            RETURN jsonb_build_object('success', false, 'error', 'Teacher account was not found in institutional records.');
        END IF;

        IF v_teacher.status::text = 'inactive' THEN
            RETURN jsonb_build_object('success', false, 'error', 'Your account has been deactivated. Please contact administration.');
        END IF;

        v_clean_phone := regexp_replace(coalesce(v_teacher.phone, ''), '[^0-9]', '', 'g');
        IF v_clean_phone IS NOT NULL AND length(v_clean_phone) >= 10 THEN
            IF regexp_replace(v_clean_sec, '[^0-9]', '', 'g') NOT IN (v_clean_phone, right(v_clean_phone, 10)) THEN
                RETURN jsonb_build_object('success', false, 'error', 'Registered mobile number does not match institutional records for this teacher account.');
            END IF;
        END IF;

        -- Save permanent password
        INSERT INTO public.portal_credentials (role, identifier, password_hash, is_temporary, updated_at)
        VALUES ('teacher', v_clean_id, p_new_password, false, clock_timestamp())
        ON CONFLICT (role, identifier) DO UPDATE
        SET password_hash = EXCLUDED.password_hash, is_temporary = false, updated_at = clock_timestamp();

        RETURN jsonb_build_object(
            'success', true,
            'role', 'teacher',
            'user', jsonb_build_object(
                'id', 't_' || v_teacher.id,
                'teacher_id', v_teacher.id,
                'name', v_teacher.name,
                'email', lower(v_teacher.login_username) || '@teachers.mips.invalid',
                'identifier', v_teacher.login_username,
                'role', 'teacher'
            )
        );
    ELSE
        RETURN jsonb_build_object('success', false, 'error', 'Invalid account role.');
    END IF;
END;
$$;

-- 4. Admin Teacher Management RPCs
CREATE OR REPLACE FUNCTION public.admin_upsert_teacher(
    p_name text,
    p_username text,
    p_phone text,
    p_temp_password text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_clean_user text := lower(trim(p_username));
    v_clean_name text := trim(p_name);
    v_clean_phone text := trim(p_phone);
    v_teacher_id bigint;
BEGIN
    IF v_clean_user IS NULL OR v_clean_user = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Staff username is required.');
    END IF;

    IF v_clean_name IS NULL OR v_clean_name = '' THEN
        RETURN jsonb_build_object('success', false, 'error', 'Staff name is required.');
    END IF;

    INSERT INTO public.teachers (name, login_username, phone, status, updated_at)
    VALUES (v_clean_name, v_clean_user, v_clean_phone, 'active', clock_timestamp())
    ON CONFLICT (login_username) DO UPDATE
    SET name = EXCLUDED.name,
        phone = EXCLUDED.phone,
        status = 'active',
        deleted_at = NULL,
        updated_at = clock_timestamp()
    RETURNING id INTO v_teacher_id;

    IF p_temp_password IS NOT NULL AND p_temp_password != '' THEN
        INSERT INTO public.portal_credentials (role, identifier, password_hash, is_temporary, updated_at)
        VALUES ('teacher', v_clean_user, p_temp_password, true, clock_timestamp())
        ON CONFLICT (role, identifier) DO UPDATE
        SET password_hash = EXCLUDED.password_hash, is_temporary = true, updated_at = clock_timestamp();
    END IF;

    RETURN jsonb_build_object(
        'success', true,
        'message', 'Teacher provisioned successfully.',
        'teacher', jsonb_build_object(
            'id', v_teacher_id,
            'name', v_clean_name,
            'login_username', v_clean_user,
            'phone', v_clean_phone
        )
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_set_teacher_active(
    p_teacher_id bigint,
    p_active boolean
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
    UPDATE public.teachers
    SET status = CASE WHEN p_active THEN 'active' ELSE 'inactive' END,
        deactivated_at = CASE WHEN p_active THEN NULL ELSE clock_timestamp() END,
        updated_at = clock_timestamp()
    WHERE id = p_teacher_id;

    RETURN jsonb_build_object('success', true, 'active', p_active);
END;
$$;

CREATE OR REPLACE FUNCTION public.admin_get_all_teachers()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_teachers jsonb;
BEGIN
    SELECT coalesce(jsonb_agg(to_jsonb(t)), '[]'::jsonb) INTO v_teachers
    FROM (
        SELECT 
            t.id,
            t.name,
            t.login_username,
            t.phone,
            t.status,
            t.created_at,
            t.updated_at,
            (SELECT count(*)::int FROM public.attendance_sessions a WHERE a.marked_by = t.id) as sessions_marked_count
        FROM public.teachers t
        WHERE t.deleted_at IS NULL
        ORDER BY t.id ASC
    ) t;

    RETURN v_teachers;
END;
$$;

